import random as ran
import turtle as t

tim = t.Turtle()
tim.shape("turtle")
t.colormode(255)
tim.speed(0)

colors = [(225, 223, 224), (199, 175, 117), (124, 36, 24), (210, 221, 213), (168, 106, 57), (222, 224, 227), (186, 158, 53), (6, 57, 83), (109, 67, 85), (113, 161, 175), (22, 122, 174), (64, 153, 138), (39, 36, 36), (76, 40, 48), (9, 67, 47), (90, 141, 53), (181, 96, 79), (132, 40, 42), (210, 200, 151), (141, 171, 155), (179, 201, 186), (172, 153, 159), (212, 183, 177), (176, 198, 203), (150, 115, 120), (202, 185, 190), (40, 72, 82), (46, 73, 62), (47, 66, 82)]
tim.penup()
x, y = -230, -225
for dot in range(1, 101):
    tim.setpos((x, y))
    tim.dot(30, ran.choice(colors))
    if dot % 10 == 0:
        y += 50
        x = -230
    else:
        x += 50




screen = t.Screen()
